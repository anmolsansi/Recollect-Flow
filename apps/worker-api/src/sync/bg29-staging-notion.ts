import { processNotionSyncJobs, type NotionWorkerOptions } from './sync.worker';

/**
 * Offline-only transport. The real NotionSyncService still constructs normal
 * Notion requests and performs projection, lookup and idempotency logic.
 * This transport NEVER delegates to global fetch, even on invalid input.
 */
export const BG29_NOTION_DATABASE_ID = 'bg29-078-offline-database';
const MOCK_TOKEN = 'bg29-078-offline-only-token';
const BASE = 'https://api.notion.com/v1';
export const BG29_NOTION_CAPTURE_IDS = Object.freeze([
  ...Array.from(
    { length: 12 },
    (_, i) => `bg29-078-url-${String(i + 1).padStart(2, '0')}`,
  ),
  ...Array.from(
    { length: 12 },
    (_, i) => `bg29-078-file-${String(i + 1).padStart(2, '0')}`,
  ),
]);

type JsonObject = Record<string, unknown>;

export interface Bg29NotionRequestRecord {
  method: string;
  path: string;
  captureId: string | null;
  status: number;
  projectionVersion: number | null;
  projectionHash: string | null;
}

export interface Bg29NotionPageRecord {
  captureId: string;
  pageId: string;
  projectionVersion: number;
  projectionHash: string;
  createCount: number;
  updateCount: number;
}

export interface Bg29StagingNotionOptions {
  /** One and only one synthetic 429 with Retry-After: 5 for this item. */
  rateLimitOnceFor?: string;
}

function obj(value: unknown): JsonObject | null {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as JsonObject)
    : null;
}

function captureFromProperties(value: unknown): string | null {
  const properties = obj(value);
  const capture = obj(properties?.['Capture ID']);
  const richText = capture?.rich_text;
  const entry = Array.isArray(richText) ? obj(richText[0]) : null;
  const text = obj(entry?.text);
  return typeof text?.content === 'string' ? text.content : null;
}

function projectionFromProperties(value: unknown): {
  version: number;
  hash: string;
} | null {
  const properties = obj(value);
  const version = obj(properties?.['Projection Version'])?.number;
  const hashProperties = obj(properties?.['Projection Hash']);
  const richText = hashProperties?.rich_text;
  const entry = Array.isArray(richText) ? obj(richText[0]) : null;
  const hash = obj(entry?.text)?.content;
  return typeof version === 'number' &&
    Number.isSafeInteger(version) &&
    version >= 1 &&
    typeof hash === 'string' &&
    hash.length > 0
    ? { version, hash }
    : null;
}

function json(body: unknown, status = 200, headers?: HeadersInit): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { 'Content-Type': 'application/json', ...headers },
  });
}

function deny(): never {
  throw new Error('BG29_STAGING_NOTION_EGRESS_DENIED');
}

export function createBg29StagingNotionHarness(
  options: Bg29StagingNotionOptions = {},
) {
  const allowed = new Set<string>(BG29_NOTION_CAPTURE_IDS);
  if (
    options.rateLimitOnceFor !== undefined &&
    !allowed.has(options.rateLimitOnceFor)
  ) {
    throw new Error('BG29 staging rate-limit target is not a fixture');
  }
  const pages = new Map<string, Bg29NotionPageRecord>();
  const requests: Bg29NotionRequestRecord[] = [];
  let injectedRateLimit = false;

  const fetcher: typeof fetch = async (input, init) => {
    // The mock accepts only the exact request shape generated by
    // NotionSyncService. A real token, other URL or redirect cannot escape.
    if (typeof input !== 'string' || !init || init.signal?.aborted) deny();
    let url: URL;
    try {
      url = new URL(input);
    } catch {
      return deny();
    }
    if (
      url.origin !== 'https://api.notion.com' ||
      url.username ||
      url.password ||
      url.search ||
      url.hash ||
      !['POST', 'PATCH'].includes(init.method ?? '') ||
      new Headers(init.headers).get('Authorization') !==
        `Bearer ${MOCK_TOKEN}` ||
      new Headers(init.headers).get('Notion-Version') !== '2022-06-28' ||
      new Headers(init.headers).get('Content-Type') !== 'application/json' ||
      typeof init.body !== 'string'
    ) {
      deny();
    }

    let body: unknown;
    try {
      body = JSON.parse(init.body);
    } catch {
      return deny();
    }
    const request = obj(body);
    if (!request) deny();

    const method = init.method!;
    const path = url.pathname;
    const log = (
      captureId: string | null,
      status: number,
      projection: { version: number; hash: string } | null = null,
    ) => {
      requests.push({
        method,
        path,
        captureId,
        status,
        projectionVersion: projection?.version ?? null,
        projectionHash: projection?.hash ?? null,
      });
    };

    if (
      method === 'POST' &&
      path === `/v1/databases/${BG29_NOTION_DATABASE_ID}/query`
    ) {
      const filter = obj(request.filter);
      const rich = obj(filter?.rich_text);
      const captureId = rich?.equals;
      if (
        request.page_size !== 2 ||
        filter?.property !== 'Capture ID' ||
        typeof captureId !== 'string' ||
        !allowed.has(captureId)
      )
        deny();

      if (options.rateLimitOnceFor === captureId && !injectedRateLimit) {
        injectedRateLimit = true;
        log(captureId, 429);
        return json({ code: 'rate_limited' }, 429, { 'Retry-After': '5' });
      }
      log(captureId, 200);
      const existing = pages.get(captureId);
      return json({ results: existing ? [{ id: existing.pageId }] : [] });
    }

    if (method === 'POST' && path === '/v1/pages') {
      const parent = obj(request.parent);
      const captureId = captureFromProperties(request.properties);
      const projection = projectionFromProperties(request.properties);
      if (
        parent?.type !== 'database_id' ||
        parent.database_id !== BG29_NOTION_DATABASE_ID ||
        !captureId ||
        !allowed.has(captureId) ||
        !projection
      )
        deny();

      const existing = pages.get(captureId);
      if (existing) {
        log(captureId, 409, projection);
        return json({ code: 'conflict' }, 409);
      }
      const pageId = `bg29-mock-page-${captureId}`;
      pages.set(captureId, {
        captureId,
        pageId,
        projectionVersion: projection.version,
        projectionHash: projection.hash,
        createCount: 1,
        updateCount: 0,
      });
      log(captureId, 200, projection);
      return json({ id: pageId });
    }

    if (method === 'PATCH' && path.startsWith('/v1/pages/')) {
      const pageId = path.slice('/v1/pages/'.length);
      const captureId = captureFromProperties(obj(request.properties));
      const projection = projectionFromProperties(request.properties);
      const existing = [...pages.values()].find(
        (page) => page.pageId === pageId,
      );
      if (
        !existing ||
        captureId !== existing.captureId ||
        !projection ||
        projection.version < existing.projectionVersion ||
        Object.keys(obj(request.properties) ?? {}).some((key) =>
          [
            'Name',
            'Status',
            'Project',
            'Topics',
            'Importance',
            'Review Date',
          ].includes(key),
        )
      )
        deny();

      existing.projectionVersion = projection.version;
      existing.projectionHash = projection.hash;
      existing.updateCount += 1;
      log(captureId, 200, projection);
      return json({ id: pageId });
    }
    return deny();
  };

  return Object.freeze({
    /** Safe inspectable copies; token, mutable maps and fetch transport are private. */
    requests: (): Bg29NotionRequestRecord[] =>
      requests.map((record) => ({ ...record })),
    pages: (): Bg29NotionPageRecord[] =>
      [...pages.values()].map((record) => ({ ...record })),
    /** Deliberately exposed for negative transport contract tests only. */
    fetcher,
    /** Staging entry: cannot pass a live token or override the HTTP transport. */
    run(
      db: D1Database,
      options: Omit<NotionWorkerOptions, 'fetcher'> = {},
    ): Promise<void> {
      return processNotionSyncJobs(db, MOCK_TOKEN, BG29_NOTION_DATABASE_ID, {
        ...options,
        fetcher,
      });
    },
  });
}
